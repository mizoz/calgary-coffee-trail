export function getShopById(id: string): CoffeeShop | undefined {
  return coffeeShops.find(shop => shop.id === id);
}

export function isOpenNow(shop: CoffeeShop): boolean {
  const now = new Date();
  const dayNames = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const today = dayNames[now.getDay()];
  
  const hours = shop.hours[today];
  if (!hours || hours.toLowerCase() === 'closed') return false;
  
  // Parse hours like "7:00 AM - 6:00 PM"
  const match = hours.match(/(\d{1,2}):(\d{2})\s*(AM|PM)\s*-\s*(\d{1,2}):(\d{2})\s*(AM|PM)/i);
  if (!match) return false;
  
  let openHour = parseInt(match[1]);
  let closeHour = parseInt(match[4]);
  if (match[3].toUpperCase() === 'PM' && openHour !== 12) openHour += 12;
  if (match[6].toUpperCase() === 'PM' && closeHour !== 12) closeHour += 12;
  if (match[3].toUpperCase() === 'AM' && openHour === 12) openHour = 0;
  if (match[6].toUpperCase() === 'AM' && closeHour === 12) closeHour = 0;
  
  const currentHour = now.getHours();
  const currentMinute = now.getMinutes();
  const currentTimeMinutes = currentHour * 60 + currentMinute;
  const openTimeMinutes = openHour * 60 + parseInt(match[2]);
  const closeTimeMinutes = closeHour * 60 + parseInt(match[5]);
  
  return currentTimeMinutes >= openTimeMinutes && currentTimeMinutes <= closeTimeMinutes;
}